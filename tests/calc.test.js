// Тесты счётной части. Запуск: node tests/calc.test.js
//
// Сам exe на машине разработки не собирается (нет Developer Pack для .NET 4.8),
// поэтому вся логика, которую вообще можно проверить без Windows, живёт в JS
// и проверяется здесь.

var Calc = require('../Web/calc.js');

var NL = String.fromCharCode(10);

var failed = 0;
var passed = 0;

function eq(expr, expected, note) {
  var got = Calc.evaluate(expr).map(function (r) { return r.text; }).join('|');
  if (got === expected) {
    passed++;
  } else {
    failed++;
    console.log('FAIL  ' + JSON.stringify(expr) + (note ? '  (' + note + ')' : ''));
    console.log('      ожидалось ' + JSON.stringify(expected));
    console.log('      получено  ' + JSON.stringify(got));
  }
}

// арифметика
eq('2 + 2', '4');
eq('10 / 4', '2.5');
eq('2^10', '1024');
eq('(1 + 2) * 3', '9');

// переменные и общая область имён на весь текст
eq('x = 5\nx * 3', '5|15');
eq('a = 2\nb = 3\na * b', '2|3|6');

// Вызовы функций без цифр не должны отбрасываться как текстовые заметки.
eq('x=10\nsqrt(x)', '10|3.16227766017');
eq('x=16\nsqrt(sqrt(x))', '16|2');
eq('x=-10\nabs(x)', '-10|10');
eq('x=10\nsqrt (x)', '10|3.16227766017');
eq('цена=16\nsqrt(цена)', '16|4');
eq('квадрат(x)=x*x\nx=3\nквадрат(x)', '|3|9');
eq('9\nsqrt(_)', '9|3');
eq('9\nsqrt(last)\nsqrt(ans)', '9|3|1.73205080757');
eq('обычная заметка (без вычислений)', '');
var unknownFunction = Calc.evaluate('x=10\nmissing(x)');
if (!unknownFunction[1].error) { failed++; console.log('FAIL  неизвестная функция должна быть ошибкой'); }
else { passed++; }

// ans — продолжение счёта следующей строкой
eq('2 + 2\nans * 10', '4|40');

// единицы измерения
eq('5 km + 300 m', '5.3 km');
eq('2 inch to cm', '5.08 cm');
eq('90 km/h to m/s', '25 m / s');

// проценты
eq('20% of 250', '50');
eq('1200 + 15%', '1380');
eq('100 - 5%', '95');
eq('15%', '0.15');
eq('10% * 200', '20');
eq('цена = 1200\nцена + 20%', '1200|1440');

// процент не должен съедать остаток от деления
eq('10 % 3', '1', 'остаток от деления');
eq('100 % 7 + 1', '3', 'остаток, потом сложение');

// пустые строки и проза результата не дают
eq('', '');
eq('Смета:\n2 + 2', '|4');
eq('# комментарий\n2 + 2', '|4');
eq('Итого:', '');
eq('просто заметка', '');

// last — результат предыдущей строки, писать его целиком не нужно
eq('2 * 2' + NL + 'last + 1', '4|5');
eq('10' + NL + 'ans * 2', '10|20', 'ans — то же самое другим именем');

// суммы по отступам, как в calque
eq(['animals:', '  cats = 2', '  dogs = 3'].join(NL), '5|2|3');
eq(['plants:', '  trees = 20', '  vegetables:', '    potatoes = 10', '    carrots = 10'].join(NL),
   '40|20|20|10|10', 'вложенный блок складывается раньше внешнего');
eq(['итого:', '  5 km', '  300 m'].join(NL), '5.3 km|5 km|300 m', 'единицы измерения складываются');
eq(['пусто:', 'дальше = 1'].join(NL), '|1', 'метка без вложенных строк суммы не даёт');

// ошибка видна, а не проглатывается
var bad = Calc.evaluate('2 +');
if (!bad[0].error) { failed++; console.log('FAIL  незаконченное выражение должно быть ошибкой'); }
else { passed++; }

// присваивание не ломает нумерацию строк
var rows = Calc.evaluate('1\n\n3');
if (rows.length !== 3) { failed++; console.log('FAIL  строк на выходе должно быть столько же, сколько на входе'); }
else { passed++; }

// «_» — короткое имя для last. math.js принимает его как обычное имя
// переменной, поэтому подменять в тексте ничего не приходится.
eq('2 * 2' + NL + '_ + 1', '4|5');
eq('2 * 2' + NL + '_', '4|4', 'одинокое подчёркивание — предыдущий результат');
eq('1200' + NL + '_ + 15%', '1200|1380', 'проценты поверх короткого имени');
eq('2 * 2' + NL + '_ + last + ans', '4|12', 'все три имени — одно значение');

// подстановка идёт по полному значению, а не по показанному: иначе продолжение
// счёта копило бы погрешность округления
eq('10 / 3' + NL + '_ * 3', '3.33333333333|10');

// «?» остаётся тернарным оператором math.js и ничего от нас не получает
eq('5 > 3 ? 111 : 222', '111');
eq('2 + 2' + NL + 'готово?', '4|', 'знак вопроса в конце фразы — не выражение');
eq('2 + 2' + NL + 'всё _ хорошо', '4|', 'подчёркивание внутри фразы — не выражение');

// точность в значащих цифрах, по умолчанию 12
eq('445/45*5', '49.4444444444');
eq('10 / 3', '3.33333333333');

Calc.setPrecision(4);
eq('10 / 3', '3.333', 'точность 4');
Calc.setPrecision(14);
eq('10 / 3', '3.3333333333333', 'точность 14');
Calc.setPrecision(12);

// значение вне допустимого диапазона игнорируется, а не ломает вывод
Calc.setPrecision(0);
eq('10 / 3', '3.33333333333', 'ноль значащих цифр не принимается');

console.log('');
console.log('пройдено ' + passed + ', провалено ' + failed);
process.exit(failed ? 1 : 0);
